#  这个脚本本身不干任何事，是给写脚本的人看的参考。
#
#  下面每一行以「# @功能」「# @选项」开头的注释，都会在
#  悬浮圆点 →「功能」页里变成一个格子：
#      功能行   [ 名称 ] [ 参数1 参数2 … ] [ 开关 ]
#      选项格   [ 名称 ] [ 控件 ]
#  「功能」段在上面，「选项」段在下面。声明顺序 = 面板上的顺序，
#  要调顺序就挪这几行注释。开头带两个 # 的不算声明（比如本行的说明）。
#
#  点右上角「保存」存盘；点「运行」会把面板上的值打印出来，方便对照。
# ================================================================


# ================================================================
#  一、功能声明
#      # @功能 名称 [参数=值 参数=值 …]
# ================================================================
#  名称后面的每一个「参数=值」都会在面板上出一个输入框；
#  值写成「甲|乙|丙」的，出的就是下拉框。
#
#  四条硬规矩（整行是按空格切词的，所以空格是唯一的分隔符）：
#    1. 名称是第一个词，里面不能有空格
#    2. 参数必须写成「名字=值」，不带 = 的词会被忽略（可以拿它当行内说明）
#    3. 参数名里也不能有空格；小字标签只有 26pt 宽，中文别超过 2 个字
#    4. 参数默认值里也不能有空格（写不下就留空，到面板上再填）
#
#  排法由参数个数自动定，不用自己管：
#    0 个 或 1 个参数 → 两个功能并排一行（各占半张卡）
#    2 个及以上参数   → 独占一整行

# ---------- 0 个参数：中间什么都不出，只有名称 + 开关
# @功能 只带开关

# ---------- 1 个参数：出一个「小字标签 + 输入框」
# 参数名随便取，x / y / 延迟 / 次数 只是习惯叫法，面板不认识它们，
# 怎么用是脚本自己读的
# @功能 一个数字参数 次数=3

# @功能 参数名随便取 重试=2

# ---------- 值是「甲|乙|丙」→ 中间出下拉框，只能在这几个里挑
# 注意：候选值里面不能有空格，有空格会被拆成两个候选；
#       面板上存过的值如果不在候选里，会自动退回第一个候选
# @功能 一个下拉参数 模式=快速|稳健|极速

# ---------- 下面三个都是 2 个及以上参数，各自独占一整行

# 2 个参数
# @功能 两个参数 延迟=0.1 次数=3

# 数字参数和下拉参数可以混着写，顺序就是声明顺序；
# 参数多了输入框会自动收窄，不会压到右边的开关
# @功能 下拉混数字 阈值=0.8 范围=全部|白名单|黑名单

# 4 个参数（再多也放得下，只是每格更窄）
# @功能 四个参数 x1=100 y1=200 x2=300 y2=400


# ================================================================
#  二、选项声明
#      # @选项 名称 类型 [默认=值] [候选=甲|乙|丙]
# ================================================================
#  类型只有四种：数字 / 文本 / 下拉 / 单选；写错了一律按「文本」处理。
#  名称和类型都是「一个词」，不能有空格；名称中文别超过 4 个字（标签 72pt）。
#  选项区一行两个，控件填满这一格剩下的宽度，控件里的文字一律左对齐。
#  「默认=」可以不写：下拉 / 单选不写就是第一个候选，数字 / 文本不写就是空。
#  和功能那行一样，声明行不能有空格 —— 所以「默认=值」里的值也不能带空格
#  （在面板上手动输入时没有这个限制，只有声明行里不能写）。

# 数字：输入框，弹出来的是小数键盘
# @选项 数字项 数字 默认=0

# 文本：输入框，普通键盘
# @选项 文本项 文本 默认=示例文字

# 下拉：点一下弹出列表挑一个
# @选项 下拉项 下拉 候选=快速|稳健|极速 默认=稳健

# 单选：横排按钮，点一下就切
# @选项 单选项 单选 候选=开|关 默认=开

# 注意：下拉 / 单选 如果漏写了「候选=」，会自动退成文本输入框，
#       免得面板上出现一个点不开的空控件。


# ================================================================
#  三、面板上的值怎么读到脚本里
# ================================================================
#  引擎不把值塞进命令行，而是写成 JSON 文件，路径放在环境变量里：
#    ZX_OPTS_FILE         选项值      {选项名: 值}
#    ZX_FUNC_PARAMS_FILE  功能参数值  {功能名: {参数名: 值}}，只含声明了参数的功能
#    ZX_FUNCS             勾了哪几个功能 —— 是「序号」，逗号隔开，如 "0,2"

import json
import os


def 读参数文件(环境变量):
    if not os.environ.get(环境变量):
        return {}
    with open(os.environ[环境变量], encoding="utf-8") as f:
        return json.load(f)


选项 = 读参数文件("ZX_OPTS_FILE")             # {"数字项": "0", "下拉项": "稳健", …}
功能参数 = 读参数文件("ZX_FUNC_PARAMS_FILE")   # {"两个参数": {"延迟": "0.1", "次数": "3"}, …}

# 脚本里声明了哪些功能（顺序和面板一致），再把 ZX_FUNCS 里的序号换成名字
功能名 = [行.strip()[len("# @功能"):].strip().split()[0]
          for 行 in open(__file__, encoding="utf-8")
          if 行.strip().startswith("# @功能")]
勾选功能 = [功能名[int(i)] for i in os.environ.get("ZX_FUNCS", "").split(",")
            if i.strip().isdigit() and int(i) < len(功能名)]
if not 勾选功能:
    勾选功能 = 功能名      # 引擎对「一个都没勾」的处理是不传 ZX_FUNCS，这里按全跑算

print("选项：", 选项)
print("功能参数：", 功能参数)
print("这次要跑的功能：", 勾选功能)
